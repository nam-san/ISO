TEMPLATES = {
    'ISO9001': ISO9001,
    'ISO14001': ISO14001,
    'ISO45001': ISO45001,
}


def seed_checklist_templates():
    """체크리스트 마스터 템플릿 시드 (최초 1회)."""
    from models import db, ChecklistTemplate
    if ChecklistTemplate.query.count() > 0:
        return
    order = 0
    for std, items in TEMPLATES.items():
        for (clause, cat, content, mandatory) in items:
            db.session.add(ChecklistTemplate(
                iso_standard=std, clause=clause, category=cat,
                content=content, is_mandatory=mandatory, sort_order=order))
            order += 1
    db.session.commit()


def standards_for(iso_standard):
    """심사의 적용표준 문자열 -> 해당 ISO 규격 리스트.
       '통합' 또는 빈 값이면 3개 규격 모두."""
    if iso_standard in TEMPLATES:
        return [iso_standard]
    return ['ISO9001', 'ISO14001', 'ISO45001']
